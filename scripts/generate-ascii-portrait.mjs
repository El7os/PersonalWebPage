// Converts public/ProfilePhoto.jpg into the ASCII art used on the landing page.
// Run with `npm run ascii-portrait` after changing the photo.

import { writeFileSync } from 'node:fs';
import sharp from 'sharp';

const SOURCE = 'public/ProfilePhoto.jpg';
const OUTPUT = 'src/components/asciiPortraitData.ts';
const COLS   = 56;
const ROWS   = 34;   // monospace cells are ~0.6 as wide as tall, so this keeps the image square
const RAMP   = ' .,:;-=+*#%@';

// Rough head-and-shoulders mask in normalised image coordinates (0..1).
function inSubject(u, v) {
    const hx = (u - 0.515) / 0.19;
    const hy = (v - 0.38) / 0.30;
    if (hx * hx + hy * hy < 1) return true;
    if (v > 0.62) return Math.abs(u - 0.5) < 0.08 + (v - 0.62) * 1.6;
    return false;
}

const { data } = await sharp(SOURCE)
    .resize(COLS, ROWS, { fit: 'fill' })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

// Luminance per cell; -1 marks background (outside the mask, or green foliage).
const lum = [];
for (let y = 0; y < ROWS; y++) {
    for (let x = 0; x < COLS; x++) {
        const i = (y * COLS + x) * 3;
        const [r, g, b] = [data[i], data[i + 1], data[i + 2]];
        const background = !inSubject((x + 0.5) / COLS, (y + 0.5) / ROWS) || (g > r + 12 && g > b);
        lum.push(background ? -1 : (0.299 * r + 0.587 * g + 0.114 * b) / 255);
    }
}

// Stretch contrast to the subject's own range.
const sorted = lum.filter(l => l >= 0).sort((a, b) => a - b);
const lo = sorted[Math.floor(sorted.length * 0.03)];
const hi = sorted[Math.floor(sorted.length * 0.97)];

const lines = [];
for (let y = 0; y < ROWS; y++) {
    let line = '';
    for (let x = 0; x < COLS; x++) {
        const l = lum[y * COLS + x];
        if (l < 0) { line += ' '; continue; }
        const t = Math.pow(Math.min(1, Math.max(0, (l - lo) / (hi - lo))), 0.9);
        line += RAMP[1 + Math.min(RAMP.length - 2, Math.floor(t * (RAMP.length - 1)))];
    }
    lines.push(line);
}

writeFileSync(OUTPUT, `// Generated by scripts/generate-ascii-portrait.mjs. Do not edit by hand.

export const ASCII_COLS = ${COLS};
export const ASCII_ROWS = ${ROWS};

export const ASCII_PORTRAIT: string[] = ${JSON.stringify(lines, null, 4)};
`);

console.log(`Wrote ${OUTPUT} (${COLS}x${ROWS})`);
